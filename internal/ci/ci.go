// Package ci generates the GitHub Actions workflow that deploys a repository
// with depper.
package ci

import (
	"fmt"
	"regexp"
	"strings"
)

// Repository is the GitHub repository depper releases are published from.
const Repository = "frgmt0/depper"

// DevVersion is the version string of a build without an injected release
// version.
const DevVersion = "dev"

// WorkflowPath is where the workflow is written, relative to the repository.
const WorkflowPath = ".github/workflows/depper.yml"

// Names of the repository secrets the workflow reads.
const (
	SecretSSHKey     = "DEPPER_SSH_KEY"
	SecretKnownHosts = "DEPPER_KNOWN_HOSTS"
	SecretEnv        = "DEPPER_ENV"
)

var (
	branchRe  = regexp.MustCompile(`^[A-Za-z0-9][A-Za-z0-9._/-]{0,127}$`)
	targetRe  = regexp.MustCompile(`^[A-Za-z0-9][A-Za-z0-9_-]{0,62}$`)
	versionRe = regexp.MustCompile(`^[0-9]+\.[0-9]+\.[0-9]+(-[0-9A-Za-z.-]+)?(\+[0-9A-Za-z.-]+)?$`)
)

// Options describe the workflow to generate.
type Options struct {
	// Target is the deployment target passed as --target ("" for none).
	Target string
	// Branch is the branch whose pushes trigger a deployment.
	Branch string
	// Version is the running depper version ("dev", "0.2.0" or "v0.2.0").
	Version string
	// Secrets reports that the configuration has a [secrets] file, so the
	// workflow feeds the DEPPER_ENV secret to `depper deploy --env-stdin`.
	Secrets bool
	// Health reports that [health] is configured, so the workflow runs
	// `depper health` after the deploy.
	Health bool
}

// ReleaseVersion returns v without a leading "v" (the GoReleaser {{.Version}}
// form used in artifact names).
func ReleaseVersion(v string) string { return strings.TrimPrefix(v, "v") }

// ArchiveName is the release archive for a version: depper_<ver>_linux_amd64.tar.gz.
// It must match archives.name_template in .goreleaser.yaml.
func ArchiveName(version string) string {
	return "depper_" + ReleaseVersion(version) + "_linux_amd64.tar.gz"
}

// Generate renders the workflow YAML. It validates every interpolated value.
func Generate(o Options) (string, error) {
	if !branchRe.MatchString(o.Branch) || strings.Contains(o.Branch, "..") || strings.HasSuffix(o.Branch, "/") || strings.HasSuffix(o.Branch, ".lock") {
		return "", fmt.Errorf("invalid branch %q", o.Branch)
	}
	if o.Target != "" && !targetRe.MatchString(o.Target) {
		return "", fmt.Errorf("invalid target name %q", o.Target)
	}
	dev := o.Version == DevVersion || o.Version == ""
	if !dev && !versionRe.MatchString(ReleaseVersion(o.Version)) {
		return "", fmt.Errorf("cannot pin depper version %q: expected a release such as v0.2.0", o.Version)
	}

	flag := ""
	group := "default"
	if o.Target != "" {
		flag = " --target " + o.Target
		group = o.Target
	}

	var b strings.Builder
	w := func(lines ...string) {
		for _, l := range lines {
			b.WriteString(l)
			b.WriteByte('\n')
		}
	}
	w(
		"# Generated by `depper ci init`. Re-run it with --force to regenerate.",
		"name: depper deploy",
		"",
		"on:",
		"  push:",
		`    branches: ["`+o.Branch+`"]`,
		"  workflow_dispatch:",
		"",
		"concurrency:",
		"  group: depper-"+group,
		"  cancel-in-progress: false",
		"",
		"permissions:",
		"  contents: read",
		"",
		"jobs:",
		"  deploy:",
		"    runs-on: ubuntu-latest",
		"    steps:",
		"      - uses: actions/checkout@v4",
		"        with:",
		"          fetch-depth: 0",
		"",
	)
	if dev {
		w(
			"      - uses: actions/setup-go@v5",
			"        with:",
			"          go-version: stable",
			"",
			"      - name: Install depper",
			"        run: go install github.com/"+Repository+"/cmd/depper@main",
			"",
		)
	} else {
		ver := ReleaseVersion(o.Version)
		w(
			"      - name: Install depper",
			"        env:",
			`          DEPPER_VERSION: "`+ver+`"`,
			"        run: |",
			"          set -eu",
			`          base="https://github.com/`+Repository+`/releases/download/v${DEPPER_VERSION}"`,
			`          archive="depper_${DEPPER_VERSION}_linux_amd64.tar.gz"`,
			`          dir="$RUNNER_TEMP/depper-install"`,
			`          mkdir -p "$dir" "$RUNNER_TEMP/bin"`,
			`          curl -fsSL -o "$dir/$archive" "$base/$archive"`,
			`          curl -fsSL -o "$dir/checksums.txt" "$base/checksums.txt"`,
			`          (cd "$dir" && sha256sum -c --ignore-missing checksums.txt)`,
			`          tar -xzf "$dir/$archive" -C "$RUNNER_TEMP/bin" depper`,
			`          echo "$RUNNER_TEMP/bin" >> "$GITHUB_PATH"`,
			"",
		)
	}
	w(
		"      - name: Configure SSH",
		"        env:",
		"          DEPPER_SSH_KEY: ${{ secrets."+SecretSSHKey+" }}",
		"          DEPPER_KNOWN_HOSTS: ${{ secrets."+SecretKnownHosts+" }}",
		"        run: |",
		"          set -eu",
		"          umask 077",
		`          dir="$RUNNER_TEMP/depper-ssh"`,
		`          mkdir -p "$dir"`,
		`          printf '%s\n' "$DEPPER_SSH_KEY" > "$dir/id"`,
		`          printf '%s\n' "$DEPPER_KNOWN_HOSTS" > "$dir/known_hosts"`,
		`          echo "DEPPER_SSH_KEY_FILE=$dir/id" >> "$GITHUB_ENV"`,
		`          echo "DEPPER_KNOWN_HOSTS_FILE=$dir/known_hosts" >> "$GITHUB_ENV"`,
		"",
		"      - name: Deploy",
	)
	if o.Secrets {
		w(
			"        env:",
			"          DEPPER_ENV: ${{ secrets."+SecretEnv+" }}",
			"        run: printf '%s' \"$DEPPER_ENV\" | depper deploy"+flag+" --env-stdin",
		)
	} else {
		w("        run: depper deploy" + flag)
	}
	if o.Health {
		w(
			"",
			"      - name: Health check",
			"        run: depper health"+flag,
		)
	}
	return b.String(), nil
}

// SecretsHelp lists the repository secrets to create and how to produce the
// known_hosts value. host may carry a "user@" prefix; port 0 means 22.
func SecretsHelp(host string, port int, secrets bool) []string {
	if i := strings.LastIndex(host, "@"); i >= 0 {
		host = host[i+1:]
	}
	if port == 0 {
		port = 22
	}
	lines := []string{
		"Create these repository secrets (Settings > Secrets and variables > Actions):",
		"  " + SecretSSHKey + "      private key that can log in to the deploy host (a dedicated deploy key)",
		"  " + SecretKnownHosts + "  the host key line(s): ssh-keyscan -p " + fmt.Sprint(port) + " " + host,
	}
	if secrets {
		lines = append(lines, "  "+SecretEnv+"        the dotenv content of [secrets].file (for example: gh secret set "+SecretEnv+" < .env.prod)")
	}
	lines = append(lines, "Verify the ssh-keyscan output against the host's real fingerprint before saving it.")
	return lines
}
